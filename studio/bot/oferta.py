def _nodes(body):
    nodes = []
    for block in body.split("\n\n"):
        lines = block.split("\n")
        if lines[0][:2].rstrip(".").isdigit() and len(lines) > 1:
            nodes.append({"tag": "h4", "children": [lines[0]]})
            lines = lines[1:]
        for line in lines:
            nodes.append({"tag": "p", "children": [line]})
    return nodes


async def url():
    """Ссылка на оферту: из .env, из кэша или новая публикация на telegra.ph."""
    if config.OFERTA_URL:
        return config.OFERTA_URL
    body = text()
    digest = hashlib.sha1(body.encode()).hexdigest()
    try:
        cached = json.loads(CACHE.read_text())
        if cached.get("digest") == digest:
            return cached["url"]
    except (OSError, ValueError):
        cached = {}
    try:
        async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=20)) as s:
            token = cached.get("token")
            if not token:
                async with s.post("https://api.telegra.ph/createAccount", data={"short_name": "Mira", "author_name": "Мира"}) as r:
                    token = (await r.json())["result"]["access_token"]
            title, rest = body.split("\n", 1)
            payload = {"access_token": token, "title": title, "author_name": "Мира",
                       "content": json.dumps(_nodes(rest.strip()), ensure_ascii=False)}
            async with s.post("https://api.telegra.ph/createPage", data=payload) as r:
                link = (await r.json())["result"]["url"]
        CACHE.write_text(json.dumps({"digest": digest, "url": link, "token": token}))
        return link
    except Exception:
        log.exception("Не удалось опубликовать оферту на telegra.ph")
        return f"https://t.me/{config.BOT_USERNAME}?start=oferta"
